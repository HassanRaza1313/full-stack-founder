// Rebuilds INDEX.md for a product repo (from product/) or an idea folder: every result by department, newest first.
// Usage: node index.mjs <product repo | idea folder>
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fail } from './lib.mjs';

const root = resolve(process.argv[2] ?? '.');
const base = existsSync(join(root, 'product')) ? join(root, 'product') : root;
if (!existsSync(base)) fail(`No such folder: ${base}`);

const living = new Set(['STATE.md', 'roadmap.md', 'product-metrics.md', 'BACKLOG.md', 'INDEX.md', 'MOVED.md']);
const today = new Date().toLocaleDateString('en-CA');

function* walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (e.name.endsWith('.md') && !(dir === base && living.has(e.name))) yield p;
  }
}

// Minimal frontmatter reader: flat "key: value" lines between --- fences.
function header(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const h = {};
  if (m) for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*(.*?)\s*(#.*)?$/);
    if (kv) h[kv[1]] = kv[2].replace(/^["']|["']$/g, '');
  }
  if (!h.summary) h.summary = (text.replace(/^---[\s\S]*?---/, '').match(/^#+\s+(.+)$/m) ?? [])[1] ?? '';
  return h;
}

const rows = {};
for (const file of walk(base)) {
  const rel = relative(base, file).replace(/\\/g, '/');
  const dept = rel.includes('/') ? rel.split('/')[0] : 'other';
  const h = header(readFileSync(file, 'utf8'));
  const date = (rel.match(/(\d{4}-\d{2}-\d{2})/) ?? [])[1] ?? '';
  const stale = h.fresh_until && h.fresh_until < today;
  (rows[dept] ??= []).push({ rel, date, topic: h.topic ?? rel.split('/').slice(1, -1).join('/'), summary: h.summary, confidence: h.confidence ?? '', stale });
}

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
const lines = ['# Index', '', `Generated by \`index.mjs\` on ${today}. Don't edit by hand. **Stale** means past its \`fresh_until\` date: refresh it before relying on it.`, ''];
const order = ['features', 'research', 'finance', 'discovery', 'iterations', 'decisions', 'design', 'audits', 'marketing', 'showcase', 'sales', 'listen', 'enablement'];
for (const dept of [...order.filter((d) => rows[d]), ...Object.keys(rows).filter((d) => !order.includes(d)).sort()]) {
  lines.push(`## ${dept}`, '', '| Date | Topic | Summary | Confidence | File |', '|---|---|---|---|---|');
  for (const r of rows[dept].sort((a, b) => b.date.localeCompare(a.date) || a.rel.localeCompare(b.rel))) {
    lines.push(`| ${r.date || '—'} | ${esc(r.topic) || '—'} | ${esc(r.summary)}${r.stale ? ' **(stale)**' : ''} | ${r.confidence || '—'} | [${r.rel.split('/').pop()}](${r.rel}) |`);
  }
  lines.push('');
}
if (!Object.keys(rows).length) lines.push('Nothing saved yet.', '');
writeFileSync(join(base, 'INDEX.md'), lines.join('\n'));
console.log(`INDEX.md: ${Object.values(rows).flat().length} results in ${Object.keys(rows).length} departments`);
